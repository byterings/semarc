import shutil
from pathlib import Path


SEMARC_MARKERS = ("generator_manifest.json", "architecture_report.json")


class OutputDirectoryError(Exception):
    pass


class OutputDirectory:
    """Prepares a clean generation directory without deleting foreign files."""

    def prepare(self, output_dir: str | Path, force: bool = False) -> Path:
        path = Path(output_dir)
        if path.exists() and not path.is_dir():
            raise OutputDirectoryError(f"Output path is not a directory: {path}")

        if path.exists() and any(path.iterdir()):
            if not force and not self.is_generated(path):
                raise OutputDirectoryError(
                    f"Output directory {path} is not empty and was not generated by SEMARC. "
                    "Choose another --output directory or pass --force to replace it."
                )
            try:
                self._clear(path)
            except OSError as error:
                raise OutputDirectoryError(f"Could not clear output directory {path}: {error}") from error

        path.mkdir(parents=True, exist_ok=True)
        return path

    def is_generated(self, path: Path) -> bool:
        return any((path / marker).is_file() for marker in SEMARC_MARKERS)

    def _clear(self, path: Path) -> None:
        for child in path.iterdir():
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()

"""Builds the OpenAPI 3.1 document of a generated API from Architecture IR.

Every target serves the same document at /openapi.json and a Swagger UI page at
/docs, so the published contract does not depend on the framework.
"""
from semarc.generator.utils.resource_views import (
    DEFAULT_PAGE_SIZE,
    MAX_PAGE_SIZE,
    field_rules,
    model_by_name,
    output_fields,
    owner_reference,
    writable_fields,
)

OPENAPI_VERSION = "3.1.0"
SWAGGER_UI_VERSION = "5.34.1"

SCALARS = {
    "STRING": {"type": "string"},
    "TEXT": {"type": "string"},
    "INTEGER": {"type": "integer"},
    "FLOAT": {"type": "number"},
    "BOOLEAN": {"type": "boolean"},
    "DATE": {"type": "string", "format": "date"},
    "DATETIME": {"type": "string", "format": "date-time"},
}
ERROR_DESCRIPTIONS = {
    "400": "Malformed JSON",
    "401": "Missing or invalid bearer token",
    "403": "The record belongs to another user",
    "404": "Record not found",
    "409": "Unique value taken or record still referenced",
    "422": "Validation failed",
    "429": "Too many attempts",
    "501": "Declared but not implemented",
}


class OpenApiBuilder:
    def build(self, ir: dict) -> dict:
        self.ir = ir
        document = {
            "openapi": OPENAPI_VERSION,
            "info": {
                "title": ir["project"],
                "version": "0.1.0",
                "description": "Generated by SEMARC from a semantic architecture specification.",
            },
            "paths": self._paths(),
            "components": {"schemas": self._schemas()},
        }
        if ir.get("auth"):
            document["components"]["securitySchemes"] = {
                "bearerAuth": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"}
            }
        return document

    def _schemas(self) -> dict:
        schemas = {
            "Error": {
                "type": "object",
                "required": ["error"],
                "properties": {
                    "error": {
                        "type": "object",
                        "required": ["code", "message"],
                        "properties": {
                            "code": {"type": "string"},
                            "message": {"type": "string"},
                            "details": {
                                "type": "object",
                                "additionalProperties": {"type": "array", "items": {"type": "string"}},
                            },
                        },
                    }
                },
            },
            "Meta": {
                "type": "object",
                "required": ["total", "limit", "offset"],
                "properties": {name: {"type": "integer"} for name in ["total", "limit", "offset"]},
            },
        }
        for model in self.ir["models"]:
            name = model["name"]
            schemas[name] = self._record_schema(model)
            schemas[f"{name}Create"] = self._input_schema(model, partial=False)
            schemas[f"{name}Update"] = self._input_schema(model, partial=True)
        auth = self.ir.get("auth")
        if auth:
            token = {
                "type": "object",
                "required": ["access_token", "token_type", "expires_in", "refresh_token", "refresh_expires_in"],
                "properties": {
                    "access_token": {"type": "string"},
                    "token_type": {"type": "string", "const": "Bearer"},
                    "expires_in": {"type": "integer"},
                    "refresh_token": {"type": "string"},
                    "refresh_expires_in": {"type": "integer"},
                },
            }
            schemas["RefreshRequest"] = {
                "type": "object",
                "required": ["refresh_token"],
                "properties": {"refresh_token": {"type": "string", "minLength": 1}},
            }
            schemas["PasswordChange"] = {
                "type": "object",
                "required": ["current_password", "new_password"],
                "properties": {
                    "current_password": {"type": "string", "format": "password"},
                    "new_password": {"type": "string", "format": "password"},
                },
            }
            schemas["Token"] = token
            schemas["Registration"] = {
                "allOf": [
                    {"$ref": "#/components/schemas/Token"},
                    {
                        "type": "object",
                        "required": ["user"],
                        "properties": {"user": {"$ref": f"#/components/schemas/{auth['model']}"}},
                    },
                ]
            }
            roles = auth.get("features", {}).get("roles")
            if roles:
                schemas["RoleChange"] = {
                    "type": "object",
                    "required": ["role"],
                    "properties": {"role": {"type": "string", "enum": roles["names"]}},
                }
            schemas["Login"] = {
                "type": "object",
                "required": [auth["identity_field"], auth["secret_field"]],
                "properties": {
                    auth["identity_field"]: {"type": "string", "minLength": 1},
                    auth["secret_field"]: {"type": "string", "minLength": 1, "format": "password"},
                },
            }
        return schemas

    def _record_schema(self, model: dict) -> dict:
        fields = {model_field["name"]: model_field for model_field in model["fields"]}
        properties = {}
        required = []
        for name, field_type in output_fields(model):
            schema = dict(SCALARS[field_type])
            if name in fields and not fields[name]["required"]:
                schema["type"] = [schema["type"], "null"]
            properties[name] = schema
            required.append(name)
        return {"type": "object", "required": required, "properties": properties}

    def _input_schema(self, model: dict, partial: bool) -> dict:
        properties = {}
        required = []
        for model_field in writable_fields(model):
            rules = field_rules(model_field)
            schema = dict(SCALARS[rules["type"]])
            if rules["type"] in {"STRING", "TEXT"}:
                if rules["min"] is not None:
                    schema["minLength"] = rules["min"]
                if rules["max"] is not None:
                    schema["maxLength"] = rules["max"]
                if rules["email"]:
                    schema["format"] = "email"
                if rules["secret"]:
                    schema["format"] = "password"
            elif rules["type"] in {"INTEGER", "FLOAT"}:
                if rules["min"] is not None:
                    schema["minimum"] = rules["min"]
                if rules["max"] is not None:
                    schema["maximum"] = rules["max"]
            if not rules["required"]:
                schema["type"] = [schema["type"], "null"]
            properties[model_field["name"]] = schema
            if rules["required"] and not partial:
                required.append(model_field["name"])

        owner = owner_reference(model)
        for reference in model["references"]:
            schema = {"type": "integer", "minimum": 1}
            if reference is owner:
                schema["description"] = "Set from the bearer token on protected routes."
            properties[reference["column"]] = schema
            if not partial and reference is not owner:
                required.append(reference["column"])

        schema = {"type": "object", "properties": properties}
        if required:
            schema["required"] = required
        return schema

    def _paths(self) -> dict:
        paths: dict = {
            "/": {"get": {"summary": "Project overview page", "tags": ["Project"], "responses": {"200": {"description": "HTML page", "content": {"text/html": {"schema": {"type": "string"}}}}}}},
            "/health": {"get": {"summary": "Health and database check", "tags": ["Project"], "responses": {"200": self._json("Healthy", self._health()), "503": self._json("Database unavailable", self._health())}}},
            "/routes": {"get": {"summary": "Route discovery", "tags": ["Project"], "responses": {"200": self._json("Declared routes", {"type": "object", "properties": {"routes": {"type": "array", "items": {"type": "string"}}}})}}},
        }
        used_ids: set[str] = set()
        for route in self.ir["routes"]:
            path = paths.setdefault(route["path"], {})
            path[route["method"].lower()] = self._operation(route, used_ids)
        return paths

    def _operation(self, route: dict, used_ids: set[str]) -> dict:
        operation = route["operation"]
        kind = operation["kind"]
        model = operation.get("model")
        tag = "Auth" if kind.startswith("auth_") else (model or "Custom")
        result = {
            "summary": SUMMARIES[kind].format(model=model, parent=operation.get("parent_model")),
            "operationId": self._operation_id(route, used_ids),
            "tags": [tag],
            "parameters": self._parameters(route),
            "responses": {},
        }
        if not result["parameters"]:
            del result["parameters"]
        if route["access"] == "protected":
            result["security"] = [{"bearerAuth": []}]
        if route.get("roles"):
            result["description"] = "Requires role: " + ", ".join(route["roles"]) + "."

        body = self._request_body(kind, model)
        if body:
            result["requestBody"] = body
        result["responses"] = self._responses(route, kind, model)
        return result

    def _request_body(self, kind: str, model: str | None) -> dict | None:
        schema = {
            "create": f"{model}Create",
            "replace": f"{model}Create",
            "update": f"{model}Update",
            "auth_register": f"{self.ir['auth']['model']}Create" if self.ir.get("auth") else None,
            "auth_login": "Login",
            "auth_set_role": "RoleChange",
            "auth_refresh": "RefreshRequest",
            "auth_logout": "RefreshRequest",
            "auth_change_password": "PasswordChange",
        }.get(kind)
        if schema is None:
            return None
        return {"required": True, "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{schema}"}}}}

    def _responses(self, route: dict, kind: str, model: str | None) -> dict:
        record = {"$ref": f"#/components/schemas/{model}"} if model else None
        success = {
            "list": ("200", self._json("Records", self._page(record))),
            "list_related": ("200", self._json("Records", self._page(record))),
            "read": ("200", self._json("Record", self._data(record))),
            "create": ("201", self._json("Created", self._data(record))),
            "replace": ("200", self._json("Replaced", self._data(record))),
            "update": ("200", self._json("Updated", self._data(record))),
            "delete": ("204", {"description": "Deleted"}),
            "auth_register": ("201", self._json("Registered", self._data({"$ref": "#/components/schemas/Registration"}))),
            "auth_login": ("200", self._json("Token issued", self._data({"$ref": "#/components/schemas/Token"}))),
            "auth_me": ("200", self._json("Current user", self._data(record))),
            "auth_set_role": ("200", self._json("User with the new role", self._data(record))),
            "auth_refresh": ("200", self._json("New tokens", self._data({"$ref": "#/components/schemas/Token"}))),
            "auth_logout": ("204", {"description": "Refresh token revoked"}),
            "auth_change_password": ("204", {"description": "Password changed; refresh tokens revoked"}),
        }
        responses = {}
        if kind in success:
            status, response = success[kind]
            responses[status] = response

        errors = []
        if kind in {"create", "replace", "update", "auth_register", "auth_login", "auth_refresh", "auth_logout", "auth_change_password"}:
            errors += ["400", "422"]
        if kind in {"create", "replace", "update", "auth_register"} and self._has_unique(model):
            errors.append("409")
        if kind == "delete":
            errors.append("409")
        if route["access"] == "protected" or kind in {"auth_login", "auth_refresh"}:
            errors.append("401")
        if route["operation"].get("owner_only") or route.get("roles"):
            errors.append("403")
        if kind == "auth_set_role":
            errors += ["404", "422"]
        if kind in {"read", "replace", "update", "delete", "list_related"}:
            errors.append("404")
        if kind in {"list", "list_related"}:
            errors.append("422")
        if kind in {"auth_register", "auth_login", "auth_refresh"}:
            errors.append("429")
        if kind == "custom":
            errors.append("501")
        for status in sorted(set(errors)):
            responses[status] = self._json(ERROR_DESCRIPTIONS[status], {"$ref": "#/components/schemas/Error"})
        return responses

    def _parameters(self, route: dict) -> list[dict]:
        parameters = [
            {"name": name, "in": "path", "required": True, "schema": {"type": "integer", "minimum": 1} if route["operation"]["kind"] != "custom" else {"type": "string"}}
            for name in route["parameters"]
        ]
        operation = route["operation"]
        if operation["kind"] in {"list", "list_related"}:
            model = model_by_name(self.ir, operation["model"])
            query = model.get("query", {"filters": {}, "sort": ["id"]})
            parameters += [
                {"name": "limit", "in": "query", "schema": {"type": "integer", "minimum": 1, "maximum": MAX_PAGE_SIZE, "default": DEFAULT_PAGE_SIZE}},
                {"name": "offset", "in": "query", "schema": {"type": "integer", "minimum": 0, "default": 0}},
                {
                    "name": "sort",
                    "in": "query",
                    "description": "Field to sort by; prefix with - for descending.",
                    "schema": {"type": "string", "enum": [prefix + field for field in query["sort"] for prefix in ("", "-")]},
                },
            ]
            parameters += [
                {"name": name, "in": "query", "description": "Equality filter.", "schema": dict(SCALARS[field_type])}
                for name, field_type in query["filters"].items()
                if name not in route["parameters"]
            ]
        return parameters

    def _operation_id(self, route: dict, used_ids: set[str]) -> str:
        parts = [route["method"].lower()]
        for segment in route["path"].strip("/").split("/"):
            if not segment:
                continue
            cleaned = segment.strip("{}").replace("-", "_")
            parts.append(("by_" if segment.startswith("{") else "") + cleaned)
        candidate = base = "_".join(parts)
        index = 2
        while candidate in used_ids:
            candidate = f"{base}_{index}"
            index += 1
        used_ids.add(candidate)
        return candidate

    def _has_unique(self, model: str | None) -> bool:
        if model is None:
            return False
        spec = model_by_name(self.ir, model)
        return any(model_field["unique"] for model_field in spec["fields"]) or any(reference["unique"] for reference in spec["references"])

    def _health(self) -> dict:
        return {
            "type": "object",
            "properties": {"status": {"type": "string"}, "project": {"type": "string"}, "database": {"type": "string"}},
        }

    def _data(self, schema: dict | None) -> dict:
        return {"type": "object", "required": ["data"], "properties": {"data": schema or {"type": "object"}}}

    def _page(self, schema: dict | None) -> dict:
        return {
            "type": "object",
            "required": ["data", "meta"],
            "properties": {
                "data": {"type": "array", "items": schema or {"type": "object"}},
                "meta": {"$ref": "#/components/schemas/Meta"},
            },
        }

    def _json(self, description: str, schema: dict) -> dict:
        return {"description": description, "content": {"application/json": {"schema": schema}}}


SUMMARIES = {
    "list": "List {model} records",
    "read": "Read one {model}",
    "create": "Create a {model}",
    "replace": "Replace a {model}",
    "update": "Partially update a {model}",
    "delete": "Delete a {model}",
    "list_related": "List {model} records of a {parent}",
    "auth_register": "Register and receive a token",
    "auth_login": "Exchange credentials for a token",
    "auth_me": "Current authenticated user",
    "auth_set_role": "Change a user's role (admin)",
    "auth_refresh": "Exchange a refresh token for new tokens",
    "auth_logout": "Revoke a refresh token",
    "auth_change_password": "Change the current user's password",
    "custom": "Declared route without generated behaviour",
}


def swagger_html(title: str) -> str:
    """Swagger UI page that renders /openapi.json (assets from unpkg, pinned)."""
    base = f"https://unpkg.com/swagger-ui-dist@{SWAGGER_UI_VERSION}"
    return "\n".join(
        [
            "<!doctype html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            f"<title>{title} API documentation</title>",
            f'<link rel="stylesheet" href="{base}/swagger-ui.css">',
            "</head>",
            "<body>",
            '<div id="swagger-ui"></div>',
            f'<script src="{base}/swagger-ui-bundle.js"></script>',
            "<script>",
            "window.onload = function () {",
            "  window.ui = SwaggerUIBundle({ url: '/openapi.json', dom_id: '#swagger-ui' });",
            "};",
            "</script>",
            "</body>",
            "</html>",
            "",
        ]
    )

import json
from pathlib import Path


SEMARC_VERSION = "0.12.0"


class ProjectFileWriter:
    """Writes target project foundation files from Architecture IR."""

    def __init__(self, output_dir: Path, reporter=None) -> None:
        self.output_dir = output_dir
        self.reporter = reporter

    def write_text(self, relative_path: str, content: str, template: str) -> None:
        path = self.output_dir / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        if self.reporter:
            self.reporter(path, template)

    def write_readme(self, ir: dict, target: str) -> None:
        self.write_text("README.md", self._readme(ir, target), "project README")

    def write_env_example(self, ir: dict, values: dict[str, str]) -> None:
        lines = [f"{key}={value}" for key, value in values.items()]
        self.write_text(".env.example", "\n".join(lines) + "\n", "env example")

    def write_manifest(self, ir: dict, target: str, profiles: list | None = None, modules: list | None = None) -> None:
        manifest = {
            "generator": target,
            "semarc_version": SEMARC_VERSION,
            "project": ir.get("project", ""),
            "generated_at": "1970-01-01T00:00:00Z",
            "profiles": profiles if profiles is not None else ir.get("profiles_loaded", []),
            "modules": modules if modules is not None else [module["name"] for module in ir.get("modules", [])],
        }
        self.write_text(
            "generator_manifest.json",
            json.dumps(manifest, indent=2) + "\n",
            "generator manifest",
        )

    def _readme(self, ir: dict, target: str) -> str:
        profiles = ir.get("profiles_loaded", [])
        modules = [module["name"] for module in ir.get("modules", [])]
        models = [model["name"] for model in ir.get("models", [])]
        routes = [f"{route['method']} {route['path']}" for route in ir.get("routes", [])]
        return "\n".join(
            [
                f"# {ir.get('project', 'SEMARC Project')}",
                "",
                f"Target: {target}",
                "",
                "Generated by SEMARC version 0.12.0.",
                "",
                "## Profiles",
                "",
                self._bullet_list(profiles),
                "",
                "## Modules",
                "",
                self._bullet_list(modules),
                "",
                "## Models",
                "",
                self._bullet_list(models),
                "",
                "## Routes",
                "",
                self._bullet_list(routes),
                "",
                "## Run Instructions",
                "",
                self._run_instructions(target),
                "",
            ]
        )

    def _bullet_list(self, values: list[str]) -> str:
        if not values:
            return "- none"
        return "\n".join(f"- {value}" for value in values)

    def _run_instructions(self, target: str) -> str:
        if target == "php":
            return "`php -S 127.0.0.1:8000 -t public`"
        if target == "fastapi":
            return "`uvicorn app.main:app --reload`"
        if target == "nestjs":
            return "`npm install` then `npm run start:dev`"
        return "Use the target framework runtime."
